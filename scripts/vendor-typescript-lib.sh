#!/usr/bin/env bash
# Vendors TypeScript's official standard library declarations (lib.*.d.ts).
# They are the fallback for projects without node_modules/typescript.
# Usage: scripts/vendor-typescript-lib.sh [directory-for-the-download]
set -euo pipefail

VERSION="5.9.3"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${1:-${TMPDIR:-/tmp}/typescript-lib}"
DEST="$ROOT/crates/galaxy-core/stubs/typescript-lib"
LIST="$ROOT/crates/galaxy-core/src/typescript/lib_files.rs"

mkdir -p "$WORK"
archive="$WORK/typescript-$VERSION.tgz"
if [[ ! -f "$archive" ]]; then
  curl -fsSL "https://registry.npmjs.org/typescript/-/typescript-$VERSION.tgz" -o "$archive"
fi
rm -rf "$WORK/package"
tar -xzf "$archive" -C "$WORK"

rm -rf "$DEST"
mkdir -p "$DEST"
cp "$WORK/package/LICENSE.txt" "$WORK/package/ThirdPartyNoticeText.txt" "$DEST/"
cp "$WORK/package/lib/"lib.d.ts "$WORK/package/lib/"lib.*.d.ts "$DEST/"

{
  echo "// Generated by scripts/vendor-typescript-lib.sh. Do not edit."
  echo "// TypeScript $VERSION standard library declarations."
  echo
  echo "pub(super) const VERSION: &str = \"$VERSION\";"
  echo
  echo "pub(super) const FILES: &[(&str, &str)] = &["
  while IFS= read -r name; do
    echo "    (\"$name\", include_str!(\"../../stubs/typescript-lib/$name\")),"
  done < <(cd "$DEST" && ls lib.d.ts lib.*.d.ts | LC_ALL=C sort)
  echo "];"
} > "$LIST"

cat > "$DEST/README.md" <<EOF
# TypeScript standard library declarations

The \`lib.*.d.ts\` files of the [\`typescript\`](https://www.npmjs.com/package/typescript)
package, version $VERSION, unchanged. Licensed under Apache-2.0; see \`LICENSE.txt\`
and \`ThirdPartyNoticeText.txt\`.

Galaxy reads a project's own \`node_modules/typescript/lib\` when it exists and
falls back to these files otherwise.

Run \`scripts/vendor-typescript-lib.sh\` to refresh them and the generated list
in \`crates/galaxy-core/src/typescript/lib_files.rs\`.
EOF
