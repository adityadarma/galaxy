#!/usr/bin/env bash
# Copies a subset of JetBrains phpstorm-stubs (Apache-2.0) into
# crates/galaxy-core/stubs/php and regenerates the include list.
#
# Usage: scripts/vendor-php-stubs.sh <path-to-phpstorm-stubs checkout>
set -euo pipefail

SRC="${1:?path to a phpstorm-stubs checkout}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$ROOT/crates/galaxy-core/stubs/php"
LIST="$ROOT/crates/galaxy-core/src/php/stub_files.rs"

EXTENSIONS=(
  Core standard SPL date json mbstring ctype pcre Reflection PDO filter hash
  curl fileinfo iconv openssl bcmath xml dom SimpleXML libxml mysqli session
  zip zlib intl gd sodium random tokenizer posix sqlite3 sockets gmp redis
)

rm -rf "$DEST"
mkdir -p "$DEST"
cp "$SRC/LICENSE" "$DEST/LICENSE"
for ext in "${EXTENSIONS[@]}"; do
  [[ -d "$SRC/$ext" ]] || { echo "missing extension: $ext" >&2; exit 1; }
  mkdir -p "$DEST/$ext"
  for file in "$SRC/$ext"/*.php; do
    # Drop attribute-only lines and blank runs; docblocks stay for hover.
    awk '
      /^[[:space:]]*#\[[^]]*\][[:space:]]*$/ { next }
      /^[[:space:]]*$/ { if (blank) next; blank = 1; print; next }
      { blank = 0; print }
    ' "$file" > "$DEST/$ext/$(basename "$file")"
  done
done

{
  echo "// Generated by scripts/vendor-php-stubs.sh. Do not edit."
  echo "// Stubs: JetBrains phpstorm-stubs, Apache-2.0 (see stubs/php/LICENSE)."
  echo
  echo "pub(super) const FILES: &[(&str, &str)] = &["
  (cd "$DEST" && find . -name '*.php' | sed 's|^\./||' | LC_ALL=C sort) | while read -r rel; do
    echo "    (\"$rel\", include_str!(\"../../stubs/php/$rel\")),"
  done
  echo "];"
} > "$LIST"

du -sh "$DEST"
