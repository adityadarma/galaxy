#!/usr/bin/env bash
# Vendors official php-src declarations for PHP 8.0 through 8.5.
# Usage: scripts/vendor-php-stubs.sh [directory-for-temporary-clones]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${1:-/var/folders/nd/4wcw343s301_457qkncdjv8r0000gn/T/opencode/php-src-stubs}"
DEST="$ROOT/crates/galaxy-core/stubs/php-src"
LIST="$ROOT/crates/galaxy-core/src/php/stub_files.rs"

# Directory name is the supported baseline. The pinned tag keeps generated
# declarations reproducible while avoiding patch releases in navigation paths.
SOURCES=(
  "8.0:8.0.30"
  "8.1:8.1.33"
  "8.2:8.2.29"
  "8.3:8.3.27"
  "8.4:8.4.14"
  "8.5:8.5.11"
)
ROOTS=(
  Zend
  ext/bcmath ext/ctype ext/curl ext/date ext/dom ext/fileinfo ext/filter ext/gd
  ext/gmp ext/hash ext/iconv ext/intl ext/json ext/libxml ext/mbstring ext/mysqli
  ext/openssl ext/pcre ext/pdo ext/posix ext/random ext/reflection ext/session
  ext/simplexml ext/sockets ext/sodium ext/spl ext/sqlite3 ext/standard ext/tokenizer
  ext/xml ext/zip ext/zlib
)

rm -rf "$DEST"
mkdir -p "$DEST" "$WORK"

for source in "${SOURCES[@]}"; do
  version="${source%%:*}"
  tag="${source#*:}"
  checkout="$WORK/php-$tag"
  if [[ ! -d "$checkout/.git" ]]; then
    git clone --depth 1 --branch "php-$tag" https://github.com/php/php-src.git "$checkout"
  fi
  target="$DEST/$version"
  mkdir -p "$target"
  for source_root in "${ROOTS[@]}"; do
    [[ -d "$checkout/$source_root" ]] || continue
    while IFS= read -r -d '' file; do
      relative="${file#"$checkout/"}"
      output="$target/$relative"
      mkdir -p "$(dirname "$output")"
      # The declarations are PHP. Remove C preprocessor guards only; attributes
      # carry useful metadata and are understood by the bundled PHP grammar.
      /usr/bin/sed \
        -e '/^[[:space:]]*#\(if\|ifdef\|ifndef\|elif\|else\|endif\)/d' \
        -e '/^[[:space:]]*function clone(/d' \
        "$file" > "$output"
    done < <(find "$checkout/$source_root" -type f -name '*.stub.php' -print0)
  done
done

{
  echo "// Generated by scripts/vendor-php-stubs.sh. Do not edit."
  echo "// Stubs: official php-src declarations for PHP 8.0 through 8.5."
  echo
  echo "pub(super) const FILES: &[&[(&str, &str)]] = &["
  for source in "${SOURCES[@]}"; do
    version="${source%%:*}"
    echo "    &["
    while IFS= read -r rel; do
      echo "        (\"$version/$rel\", include_str!(\"../../stubs/php-src/$version/$rel\")),"
    done < <(cd "$DEST/$version" && find . -type f -name '*.stub.php' | /usr/bin/sed 's|^./||' | LC_ALL=C sort)
    echo "    ],"
  done
  echo "];"
} > "$LIST"

cat > "$DEST/README.md" <<'EOF'
# PHP built-in declarations

Generated from official [`php-src`](https://github.com/php/php-src) release tags:

- PHP 8.0 from PHP-8.0.30
- PHP 8.1 from PHP-8.1.33
- PHP 8.2 from PHP-8.2.29
- PHP 8.3 from PHP-8.3.27
- PHP 8.4 from PHP-8.4.14
- PHP 8.5 from PHP-8.5.11

Run `scripts/vendor-php-stubs.sh` to refresh the corpus and generated include list.
PHP versions before 8.0 are intentionally unsupported: upstream did not publish
an equivalent maintained PHP declaration corpus for those releases.
EOF

du -sh "$DEST"
